// gen-tool-catalog documents the actual MCP inventories without calling a backend.
package main

import (
	"bytes"
	"encoding/base64"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/corezoid/simulator-ai/internal/auth"
	"github.com/corezoid/simulator-ai/internal/mcpserver"
	"github.com/corezoid/simulator-ai/internal/publicapi"
)

type availability struct{ read, write []string }

func generate() ([]byte, error) {
	profiles := []string{"read", "graph-read", "graph-create", "smart-forms", "reactions-read", "console", "console-full", "delegated-read", "graph-read (bound)", "reactions-read (bound)"}
	catalog := map[string]*availability{}
	for _, label := range profiles {
		profile := strings.TrimSuffix(label, " (bound)")
		config := publicapi.Config{Origin: "http://127.0.0.1:1", Workspace: "catalog", APIKey: "synthetic", Profile: profile}
		if strings.HasSuffix(label, " (bound)") {
			config.ActorID = "catalog-actor"
		}
		if profile != "delegated-read" {
			// A desktop process (no host Authorization) also lists the account tools.
			config.Account = auth.NewSession(auth.Options{Origin: config.Origin, ConfigDir: "/nonexistent"})
		} else {
			config.APIKey = ""
			config.DelegatedToken = base64.RawURLEncoding.EncodeToString(make([]byte, 32))
		}
		client, err := publicapi.New(config)
		if err != nil {
			return nil, fmt.Errorf("catalog %s: %w", label, err)
		}
		for name, entry := range mcpserver.New(client).ListTools() {
			if catalog[name] == nil {
				catalog[name] = &availability{}
			}
			if entry.Tool.Annotations.ReadOnlyHint != nil && *entry.Tool.Annotations.ReadOnlyHint {
				catalog[name].read = append(catalog[name].read, "`"+label+"`")
			} else {
				catalog[name].write = append(catalog[name].write, "`"+label+"`")
			}
		}
	}
	names := make([]string, 0, len(catalog))
	for name := range catalog {
		names = append(names, name)
	}
	sort.Strings(names)
	var out strings.Builder
	out.WriteString("# Tool availability\n\n<!-- Generated by cmd/gen-tool-catalog; do not edit. Run make docs. -->\n\n")
	out.WriteString("[Tool guide](tool-reference.md) · [API mappings](api-tools.md) · [Console workflows](console.md)\n\n")
	out.WriteString("This table comes from the server's actual profile registrations. `read` is the default.\n")
	out.WriteString("Bound profiles set `SIMULATOR_AI_ACTOR` and expose only the bound actor/layer counter.\n")
	out.WriteString("Every unbound profile except `delegated-read` also lists the account tools (`login`, `logout`, `whoami`,\n")
	out.WriteString("`workspaces_list`, `workspace_set`); a host that sets `SIMULATOR_AI_AUTHORIZATION` does not.\n")
	out.WriteString("Read-only means the MCP annotation is explicitly true; all other tools appear under **May write**.\n")
	out.WriteString("Annotations do not grant permissions or rule out documented backend maintenance side effects.\n")
	out.WriteString("A shared tool name can have different inputs and projections across profiles: inspect the running\n")
	out.WriteString("server's `tools/list` schema before calling it. Hosts may further restrict the available catalog.\n\n")
	out.WriteString("| Tool | Read-only in | May write in |\n| --- | --- | --- |\n")
	for _, name := range names {
		row := catalog[name]
		fmt.Fprintf(&out, "| `%s` | %s | %s |\n", name, strings.Join(row.read, ", "), strings.Join(row.write, ", "))
	}
	return []byte(out.String()), nil
}

func run(check bool) error {
	const path = "docs/tool-catalog.md"
	data, err := generate()
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, data) {
			return fmt.Errorf("tool catalog drift: run make docs")
		}
		return nil
	}
	return os.WriteFile(path, data, 0644)
}

func main() {
	check := flag.Bool("check", false, "check the committed catalog without writing")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
