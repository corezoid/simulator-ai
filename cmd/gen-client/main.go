// gen-client generates the deliberately small read profile from pinned public OpenRPC.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type Schema struct {
	Type        string            `json:"type"`
	Description string            `json:"description"`
	Properties  map[string]Schema `json:"properties"`
	Items       *Schema           `json:"items"`
}
type Param struct {
	Name   string `json:"name"`
	Schema Schema `json:"schema"`
}
type Method struct {
	Name     string  `json:"name"`
	Audience string  `json:"x-audience"`
	Scope    string  `json:"x-scope"`
	Params   []Param `json:"params"`
	Result   struct {
		Schema Schema `json:"schema"`
	} `json:"result"`
}
type Document struct {
	Methods []Method `json:"methods"`
}

func main() {
	input := flag.String("input", "contracts/public-openrpc.json", "pinned public profile projection")
	output := flag.String("output", "internal/publicapi/types.gen.go", "generated types")
	check := flag.Bool("check", false, "compare without writing")
	flag.Parse()
	b, e := os.ReadFile(*input)
	if e != nil {
		fail(e)
	}
	out, e := generate(b)
	if e != nil {
		fail(e)
	}
	if *check {
		current, e := os.ReadFile(*output)
		if e != nil {
			fail(e)
		}
		if !bytes.Equal(current, out) {
			fail(fmt.Errorf("generated client drift: run make generate"))
		}
		return
	}
	if e = os.WriteFile(*output, out, 0644); e != nil {
		fail(e)
	}
}
func fail(e error) { fmt.Fprintln(os.Stderr, e); os.Exit(1) }
func generate(data []byte) ([]byte, error) {
	var d Document
	if e := json.Unmarshal(data, &d); e != nil {
		return nil, e
	}
	methods := map[string]Method{}
	for _, m := range d.Methods {
		if m.Audience != "public" {
			return nil, fmt.Errorf("non-public method %s", m.Name)
		}
		if _, ok := methods[m.Name]; ok {
			return nil, fmt.Errorf("duplicate method %s", m.Name)
		}
		methods[m.Name] = m
	}
	if len(methods) != 3 {
		return nil, fmt.Errorf("profile must contain exactly three methods")
	}
	var out strings.Builder
	out.WriteString("// Code generated by cmd/gen-client from contracts/public-openrpc.json; DO NOT EDIT.\npackage publicapi\n\n")
	names := []string{"actor/get", "form/get", "graph/layer/actors/list"}
	for i, name := range names {
		m, ok := methods[name]
		if !ok {
			return nil, fmt.Errorf("missing %s", name)
		}
		if m.Scope == "" {
			return nil, fmt.Errorf("missing scope %s", name)
		}
		typename := []string{"ActorRequest", "FormRequest", "LayerRequest"}[i]
		fmt.Fprintf(&out, "// %s is the wire request for public %s (scope %s).\ntype %s struct {\n", typename, name, m.Scope, typename)
		for _, p := range m.Params {
			t, e := wireType(p.Schema)
			if e != nil {
				return nil, fmt.Errorf("%s/%s: %w", name, p.Name, e)
			}
			fmt.Fprintf(&out, "// Source: %s param %s.\n%s %s `json:%q`\n", name, p.Name, goName(p.Name), t, p.Name+",omitempty")
		}
		out.WriteString("}\n\n")
	}
	actor := methods["actor/get"].Result.Schema
	if e := emit(&out, "Actor", actor, []string{"id", "title", "description", "formId", "status", "ref"}, "actor/get"); e != nil {
		return nil, e
	}
	if e := emit(&out, "Form", methods["form/get"].Result.Schema, []string{"id", "title", "description", "type", "parentId"}, "form/get"); e != nil {
		return nil, e
	}
	list := methods["graph/layer/actors/list"].Result.Schema.Properties["list"]
	if list.Type != "array" || list.Items == nil {
		return nil, fmt.Errorf("layer list is not an array")
	}
	node := *list.Items
	if e := emit(&out, "Position", node.Properties["position"], []string{"x", "y"}, "graph/layer/actors/list position"); e != nil {
		return nil, e
	}
	if node.Properties["actor"].Type != "object" {
		return nil, fmt.Errorf("node actor is not object")
	}
	// Check every projected actor property at the nested boundary too.
	for _, k := range []string{"id", "title", "description", "formId", "status", "ref"} {
		if node.Properties["actor"].Properties[k].Type != actor.Properties[k].Type {
			return nil, fmt.Errorf("nested actor type drift %s", k)
		}
	}
	if e := emit(&out, "Placement", node, []string{"laId", "id", "accessDenied"}, "graph/layer/actors/list"); e != nil {
		return nil, e
	}
	// Composite fields are separate generated wrapper, so scalar projection never falls back to an unknown bag.
	out.WriteString("// LayerNode projects a placement plus its authorized actor and geometry.\ntype LayerNode struct { Placement; Position *Position `json:\"position,omitempty\"`; Actor *Actor `json:\"actor,omitempty\"` }\n")
	out.WriteString("// LayerResult is one public graph/layer/actors/list page; no inferred total.\ntype LayerResult struct { List []LayerNode `json:\"list\"` }\n")
	return format.Source([]byte(out.String()))
}
func emit(out *strings.Builder, name string, s Schema, fields []string, source string) error {
	if s.Type != "object" {
		return fmt.Errorf("%s: expected object", source)
	}
	sort.Strings(fields)
	fmt.Fprintf(out, "// %s contains the R1 metadata projection of public %s.\ntype %s struct {\n", name, source, name)
	for _, key := range fields {
		p, ok := s.Properties[key]
		if !ok {
			return fmt.Errorf("%s: missing field %s", source, key)
		}
		t, e := wireType(p)
		if e != nil {
			return e
		}
		fmt.Fprintf(out, "// Source: public %s result.%s. %s\n%s *%s `json:%q`\n", source, key, strings.ReplaceAll(p.Description, "\n", " "), goName(key), t, key+",omitempty")
	}
	out.WriteString("}\n\n")
	return nil
}
func wireType(s Schema) (string, error) {
	switch s.Type {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		if s.Items != nil && s.Items.Type == "string" {
			return "[]string", nil
		}
	}
	return "", fmt.Errorf("unsupported schema type %q", s.Type)
}
func goName(s string) string {
	switch s {
	case "id":
		return "ID"
	case "accId":
		return "AccID"
	case "actorId":
		return "ActorID"
	case "formId":
		return "FormID"
	case "parentId":
		return "ParentID"
	case "laId":
		return "LaID"
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
