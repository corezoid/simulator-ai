// gen-cdu-reference writes the CDU v2 reference documents the console embeds (protocol, examples
// and the per-type notes the components document adds to the live catalog) from the sources of
// truth: sim-api's vendored page-config contract and catalog manifest, and the ui-kit's help bundle
// and CI-validated example pages. It reads both repositories at a commit through git, never their
// working trees, and records the commits in each document, so -check regenerates exactly what was
// committed. Offline checks use the public input projection; source checks require both checkouts.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// outDir holds the generated documents, embedded by internal/mcpserver.
const outDir = "internal/mcpserver/cdureference"

// source is one repository read at one commit.
type source struct {
	name, dir, rev string
}

func (s source) read(path string) ([]byte, error) {
	out, err := exec.Command("git", "-C", s.dir, "show", s.rev+":"+path).Output()
	if err != nil {
		return nil, fmt.Errorf("%s %s:%s: %w", s.name, short(s.rev), path, err)
	}
	return out, nil
}

// header names the commits a document was generated from; -check reads them back.
func header(sim, kit source) string {
	return fmt.Sprintf("Generated by cmd/gen-cdu-reference from sim-api %s and simulator-ui-kit %s; do not edit.", sim.rev, kit.rev)
}

var headerRevs = regexp.MustCompile(`from sim-api ([0-9a-f]{40}) and simulator-ui-kit ([0-9a-f]{40})`)

func main() {
	simDir := flag.String("sim-api", envOr("SIM_API_DIR", sibling("sim-api")), "sim-api checkout")
	kitDir := flag.String("ui-kit", envOr("UI_KIT_DIR", sibling("simulator-ui-kit")), "simulator-ui-kit checkout")
	simRev := flag.String("sim-api-rev", "origin/develop", "sim-api commit to read")
	kitRev := flag.String("ui-kit-rev", "origin/develop", "simulator-ui-kit commit to read")
	check := flag.Bool("check", false, "regenerate from committed public inputs and compare without writing")
	verify := flag.Bool("verify-sources", false, "verify inputs and output against the recorded source commits (requires both checkouts)")
	flag.Parse()
	sim, kit := source{"sim-api", *simDir, *simRev}, source{"simulator-ui-kit", *kitDir, *kitRev}
	if *check || *verify {
		err := checkSnapshot(outDir)
		if err == nil && *verify {
			err = checkDrift(sim, kit, outDir)
		}
		if err != nil {
			fail(err)
		}
		return
	}
	var err error
	if sim.rev, err = resolve(sim); err != nil {
		fail(err)
	}
	if kit.rev, err = resolve(kit); err != nil {
		fail(err)
	}
	files, err := generate(sim, kit)
	if err != nil {
		fail(err)
	}
	for name, body := range files {
		if err = os.WriteFile(filepath.Join(outDir, name), body, 0o644); err != nil {
			fail(err)
		}
	}
}

// checkDrift regenerates at the commits dir/protocol.md records and compares every document.
func checkDrift(sim, kit source, dir string) error {
	current, err := os.ReadFile(filepath.Join(dir, "protocol.md"))
	if err != nil {
		return err
	}
	m := headerRevs.FindSubmatch(current)
	if m == nil {
		return errors.New("protocol.md has no source header: run make generate")
	}
	sim.rev, kit.rev = string(m[1]), string(m[2])
	for _, s := range []source{sim, kit} {
		if exec.Command("git", "-C", s.dir, "cat-file", "-e", s.rev+"^{commit}").Run() != nil {
			return fmt.Errorf("source check requires %s %s in %s", s.name, short(s.rev), s.dir)
		}
	}
	files, err := generate(sim, kit)
	if err != nil {
		return err
	}
	return compareFiles(dir, files)
}

// generate renders every document from the two sources.
func generate(sim, kit source) (map[string][]byte, error) {
	in, err := readInputs(sim, kit)
	if err != nil {
		return nil, err
	}
	return renderInputs(header(sim, kit), in)
}

func renderInputs(head string, in *inputs) (map[string][]byte, error) {
	projection, err := snapshot(in, head)
	if err != nil {
		return nil, err
	}
	protocol, err := renderProtocol(head, in)
	if err != nil {
		return nil, err
	}
	examples, err := renderExamples(head, in)
	if err != nil {
		return nil, err
	}
	types, err := renderTypeNotes(head, in)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{"inputs.json": projection, "protocol.md": protocol, "examples.md": examples, "types.json": types}, nil
}

func resolve(s source) (string, error) {
	out, err := exec.Command("git", "-C", s.dir, "rev-parse", "--verify", s.rev+"^{commit}").Output()
	if err != nil {
		return "", fmt.Errorf("%s: no commit %s in %s: %w", s.name, s.rev, s.dir, err)
	}
	return strings.TrimSpace(string(out)), nil
}

// sibling is a checkout next to this repository's main checkout (a worktree included).
func sibling(name string) string {
	out, err := exec.Command("git", "rev-parse", "--path-format=absolute", "--git-common-dir").Output()
	if err != nil {
		return filepath.Join("..", name)
	}
	return filepath.Join(filepath.Dir(filepath.Dir(strings.TrimSpace(string(out)))), name)
}

func envOr(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

func short(rev string) string {
	if len(rev) > 10 {
		return rev[:10]
	}
	return rev
}

func fail(e error) { fmt.Fprintln(os.Stderr, e); os.Exit(1) }
